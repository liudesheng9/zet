        log(`Explain: ${planned ? `${planned.parts || 0} Derivation parts in ${(planned.jobs || []).length} DeepSeek jobs` : 'plan gave no output'}; ${reported ? `${(reported.models || []).length} models reported` : 'no report'}; ${refused.length} refused.`)
