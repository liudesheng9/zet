    const kopts = { dsh: SK, skills: ['asd-ste100-zh'], effort: Z.DSH_EFFORT, phase: 'Organize', writes: `${SK}\\out`, remove: 'delete', keep: true }
    await Z.drive('organize: skeleton', { ...kopts, command: kstep('plan') })
