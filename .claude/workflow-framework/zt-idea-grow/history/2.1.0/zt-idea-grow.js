// ==== module script v1 ====
// One agent runs one fixed shell command and reports its output. Scripts do the structural work; the agent
// only relays. By default the command's last stdout line must be compact JSON, which becomes the output.
const WFP_SCRIPT_SCHEMA = {
  type: 'object',
  properties: {
    exit_code: { type: 'integer' },
    last_line: { type: 'string', description: 'the last non-empty line of stdout, verbatim' },
    tail: { type: 'string', description: 'the last 2000 characters of stdout and stderr' },
  },
  required: ['exit_code', 'last_line', 'tail'],
}
async function wfpScript(ctx, p) {
  const tool = p.shell === 'bash' ? 'Bash' : 'PowerShell'
  const r = await ctx.agent(`Run one command and report its output. Use the ${tool} tool${p.cwd ? ` with the working folder ${p.cwd}` : ''} and timeout ${p.timeoutMs || 600000}.

COMMAND:
${p.command}

1. Run the COMMAND exactly as written. Change nothing in it.
2. Run no other command. Do not fix, retry, or investigate anything. Do not edit files.
3. Return exit_code, last_line (the last non-empty line of stdout, verbatim), and tail (the last 2000 characters of the output).`,
    { role: p.role || 'runner', schema: WFP_SCRIPT_SCHEMA, label: p.label || `${ctx.label}: script` })
  if (!r) throw new Error('script: the runner returned nothing')
  if (!(p.okExit || [0]).includes(r.exit_code)) throw new Error(`script: exit code ${r.exit_code}: ${String(r.tail).slice(-600)}`)
  if (p.json === false) return { exit_code: r.exit_code, last_line: r.last_line, tail: r.tail }
  try { return JSON.parse(r.last_line) } catch (e) { throw new Error(`script: the last stdout line is not JSON: ${String(r.last_line).slice(0, 300)}`) }
}
defineModule({
  id: 'script', version: '1',
  summary: 'One agent runs one fixed shell command; the last stdout line (compact JSON) is the output.',
  params: {
    command: { type: 'string', required: true, description: 'the exact command; templates allowed' },
    shell: { type: 'string', default: 'powershell', enum: ['powershell', 'bash'], description: 'the tool that runs it' },
    cwd: { type: 'string', description: 'working folder for the command' },
    json: { type: 'boolean', default: true, description: 'parse the last stdout line as JSON' },
    okExit: { type: 'array', default: [0], description: 'exit codes that count as success' },
    timeoutMs: { type: 'number', default: 600000, description: 'the tool timeout in ms' },
    role: { type: 'string', default: 'runner', role: true, description: 'the declared role that relays the command' },
    label: { type: 'string', description: 'progress label' },
  },
  run: wfpScript,
})
